/** The admin language: the one chosen in this browser (cookie), English by default. */
function admin_lang(): string {
    $lang = $_COOKIE[ADMIN_LANG_COOKIE] ?? '';
    return in_array($lang, ADMIN_LANGS, true) ? $lang : 'en';
}

/** Translated text for a key, falling back to English; {name} parts are replaced from $vars. */
function t(string $key, array $vars = []): string {
    $text = ADMIN_STRINGS[admin_lang()][$key] ?? ADMIN_STRINGS['en'][$key] ?? $key;
    foreach ($vars as $name => $value) {
        $text = str_replace('{' . $name . '}', (string) $value, $text);
    }
    return $text;
}
